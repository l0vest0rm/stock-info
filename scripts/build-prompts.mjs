#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { feedCategoryCatalogHash } from "./lib/information-feed-extraction.mjs";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(SCRIPT_DIR, "..");

const promptEntries = [
  {
    exportName: "REPORT_ANALYZE_SYSTEM_PROMPT",
    source: "prompts/company/report-analyze-system.md",
  },
  {
    exportName: "REPORT_ANALYZE_USER_PROMPT",
    source: "prompts/company/report-analyze-user.md",
  },
  {
    exportName: "REPORT_DISCOVERY_PROMPT",
    source: "prompts/company/report-discovery.md",
  },
  {
    exportName: "TOPIC_BATCH_SYSTEM_PROMPT",
    source: "prompts/knowledge/topic-batch-system.md",
  },
  {
    exportName: "TOPIC_BATCH_USER_PROMPT",
    source: "prompts/knowledge/topic-batch-user.md",
  },
  {
    exportName: "INFORMATION_FEED_DOCUMENT_ANALYSIS_SYSTEM_PROMPT",
    source: "prompts/information-feed/document-analysis-system.md",
  },
  {
    exportName: "INFORMATION_FEED_DOCUMENT_ANALYSIS_USER_PROMPT",
    source: "prompts/information-feed/document-analysis-user.md",
  },
  {
    exportName: "RESEARCH_FINANCIAL_ANALYSIS_PROMPT",
    source: "prompts/research/financial-analysis.md",
  },
  {
    exportName: "RESEARCH_OPERATING_ANALYSIS_PROMPT",
    source: "prompts/research/operating-analysis.md",
  },
  {
    exportName: "MACRO_ANALYSIS_PROMPT",
    source: "prompts/macro.md",
  },
];

const generatedTsPath = resolve(PROJECT_ROOT, "src/generated/prompt-text.ts");
const generatedMjsPath = resolve(PROJECT_ROOT, "scripts/generated/prompt-text.mjs");

const lines = [
  "// Generated by scripts/build-prompts.mjs. Do not edit by hand.",
  "",
];

for (const entry of promptEntries) {
  const text = readFileSync(resolve(PROJECT_ROOT, entry.source), "utf8").trim();
  lines.push(`export const ${entry.exportName} = ${JSON.stringify(text)};`);
}

lines.push("");

const output = `${lines.join("\n")}`;

mkdirSync(dirname(generatedTsPath), { recursive: true });
mkdirSync(dirname(generatedMjsPath), { recursive: true });
writeFileSync(generatedTsPath, output);
writeFileSync(generatedMjsPath, output);

// Freeze the same contract hashes into both runtimes; do not change the LLM
// contract merely because the persistence format changes.
const feedConfig = JSON.parse(readFileSync(resolve(PROJECT_ROOT, 'config/knowledge/information-feed.json'), 'utf8'));
const hash = (text) => createHash('sha256').update(text).digest('hex');
const feedPrompt = (file) => readFileSync(resolve(PROJECT_ROOT, `prompts/information-feed/${file}`), 'utf8').trim();
const contract = {
  contractVersion: feedConfig.tagContract,
  promptHash: hash(feedPrompt('document-analysis-system.md') + feedPrompt('document-analysis-user.md')),
  categoryCatalogHash: feedCategoryCatalogHash(),
  candidatePolicyHash: hash(JSON.stringify(feedConfig.companyCandidates || {})),
  model: 'gpt-6-luna',
};
const legacyContracts = JSON.parse(readFileSync(resolve(PROJECT_ROOT, 'config/knowledge/information-feed-legacy-contracts.json'), 'utf8'));
if (!Array.isArray(legacyContracts) || new Set([contract, ...legacyContracts].map((entry) => entry.contractVersion)).size !== legacyContracts.length + 1) {
  throw new Error('feed extraction contract versions must be distinct');
}
// The offline storage migration specifically verifies v5 provenance, not the
// most recent previous prompt. Readers accept every explicitly frozen contract.
const legacyContract = legacyContracts.find((entry) => entry.contractVersion === 'feed-tag-v5');
if (!legacyContract) throw new Error('v5 feed extraction contract is required for the storage backfill');
const contractOutput = `// Generated by scripts/build-prompts.mjs. Do not edit by hand.\nexport const FEED_EXTRACTION_CONTRACT = ${JSON.stringify(contract, null, 2)};\nexport const LEGACY_FEED_EXTRACTION_CONTRACTS = ${JSON.stringify(legacyContracts, null, 2)};\nexport const LEGACY_FEED_EXTRACTION_CONTRACT = ${JSON.stringify(legacyContract, null, 2)};\n`;
writeFileSync(resolve(PROJECT_ROOT, 'src/generated/information-records-contract.ts'), contractOutput);
writeFileSync(resolve(PROJECT_ROOT, 'scripts/generated/information-records-contract.mjs'), contractOutput);

// The ontology owns category names; UI labels must not become a second catalog.
const ontology = JSON.parse(readFileSync(resolve(PROJECT_ROOT, 'config/knowledge/knowledge-ontology.json'), 'utf8'));
const categories = ontology.informationExtraction.categories;
for (const [id, rule] of Object.entries(categories)) {
  if (!rule.label || !['required', 'optional', 'forbidden'].includes(rule.periodPolicy)
    || !rule.informationTypes.length || rule.informationTypes.some((type) => !ontology.informationExtraction.informationTypes.includes(type))) {
    throw new Error(`invalid information category: ${id}`);
  }
}
writeFileSync(resolve(PROJECT_ROOT, 'web/src/config/information-feed-labels.json'),
  JSON.stringify({ categories: Object.fromEntries(Object.entries(categories).map(([id, rule]) => [id, rule.label])) }, null, 2) + '\n');
